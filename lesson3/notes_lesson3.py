# the sprint
# one goal
# fixed time box: 2 weeks, 1 month
# goal doesn't change
# reviews, retros go inside the sprint


# Scrum events
# planning - start sprint - what can we do and how?
# daily scrum - every day - are we on track?
# sprint review - end sprint - show the result, get feedback?
# sprint retrospective - very end - how can we work better?


# Daily scrum - standup
# 15 min, same place same time
# what I did? what will I do? blockers?


