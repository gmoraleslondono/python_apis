# 4 Agile values
# 1. Individuals and interactions over processes and tools
#    → Good communication and teamwork are more important than tools or strict processes.
# 2. Working software over comprehensive documentation
#    → Having working software is more important than writing lots of documentation.
# 3. Customer collaboration over contract negotiation
#    → Working closely with the customer is more important than focusing only on the contract.
# 4. Responding to change over following a plan
#    → Being able to adapt to changes is more important than strictly following the original plan.


