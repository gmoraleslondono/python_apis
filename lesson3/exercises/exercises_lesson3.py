# Exercise 8
# Write a Definition of Done for a team of four developers. Include at least five points.
# Solution:
# Definition of Done
# The application works as expected.
# The application works correctly on mobile and desktop.
# All text is readable and displayed correctly.
# All buttons and links are clickable and work as expected.
# All images load correctly.
# The code has been reviewed by another developer.
# The application has been tested and no critical bugs remain.


